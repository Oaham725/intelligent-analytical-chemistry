"""G10 teaching baseline. Synthetic data; Python standard library only.
Run from any working directory. Results are written beside this script.
"""
import argparse
import csv
import hashlib
import json
import math
import platform
from datetime import datetime, timezone
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'data'
OUT = ROOT / 'results'


def read_csv(name):
    with (DATA / name).open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def cosine(x, y):
    if any(not math.isfinite(v) or v < 0 for v in [*x.values(), *y.values()]):
        raise ValueError('Intensities must be finite and nonnegative')
    nx = math.sqrt(sum(v*v for v in x.values()))
    ny = math.sqrt(sum(v*v for v in y.values()))
    if not nx or not ny:
        raise ValueError('Zero spectrum has undefined cosine')
    return sum(v*y.get(mz, 0) for mz, v in x.items()) / (nx*ny)


def lri(rt, low, high, n):
    if not all(math.isfinite(v) for v in (rt, low, high, n)):
        raise ValueError('Nonfinite retention input')
    if high <= low or not low <= rt <= high:
        raise ValueError('Unknown must be bracketed by ordered adjacent alkanes')
    return 100 * (n + (rt-low)/(high-low))


def rank(spectrum, ri, spectra, candidates, sigma=15):
    if sigma <= 0:
        raise ValueError('RI tolerance must be positive')
    rows = []
    for candidate in candidates:
        cid = candidate['candidate_id']
        sim = cosine(spectrum, spectra[cid])
        delta = ri - float(candidate['reference_ri'])
        retention = math.exp(-0.5*(delta/sigma)**2)
        rows.append(dict(candidate=cid, cosine=sim, delta_ri=delta,
                         ri_score=retention, score=0.7*sim+0.3*retention))
    return sorted(rows, key=lambda r: (-r['score'], r['candidate']))


def decision(rows, rs):
    gap = rows[0]['score'] - rows[1]['score']
    if rs < 1.0:
        return '拒判：共洗脱风险'
    if rows[0]['score'] < 0.80 or gap < 0.05:
        return '拒判：证据不足或候选过近'
    return '优先验证候选；未确证'


def write_csv(name, rows):
    with (OUT / name).open('w', encoding='utf-8-sig', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def write_lab_data(decisions, ranking):
    lab = ROOT.parents[1] / 'assets' / 'labs' / 'g10'
    if not (lab / 'index.html').is_file():
        return
    samples = {}
    for outcome in decisions:
        sample_id = outcome['sample']
        candidates = [
            {key: row[key] for key in ('candidate', 'cosine', 'delta_ri')}
            for row in ranking if row['sample'] == sample_id
        ]
        samples[sample_id] = dict(ri=outcome['ri'], rs=outcome['rs'], candidates=candidates)
    data = json.dumps(samples, ensure_ascii=False, indent=2, allow_nan=False)
    (lab / 'data.js').write_text(
        f'// Generated by code/ch10_g10/run_case.py.\nconst G10_DATA = {data};\n',
        encoding='utf-8',
    )


def self_test():
    """Check invariance, bounds and the two rejection mechanisms."""
    assert math.isclose(cosine({51: 3, 91: 4}, {51: 6, 91: 8}), 1)
    assert cosine({51: 1}, {91: 1}) == 0
    assert math.isclose(lri(7.6, 6, 8, 8), 880)
    assert math.isclose(lri(7.8, 6.2, 8.2, 8), 880)
    for action in (lambda: cosine({}, {1: 1}),
                   lambda: cosine({1: -1}, {1: 1}),
                   lambda: lri(9, 6, 8, 8)):
        try:
            action()
        except ValueError:
            pass
        else:
            raise AssertionError('Invalid input was not rejected')
    assert decision([{'score': .99}, {'score': .70}], .7).startswith('拒判')
    assert decision([{'score': .99}, {'score': .98}], 1.5).startswith('拒判')
    print('Self-test passed: scale invariance, disjoint peaks, LRI, invalid inputs, refusal.')


def plot(all_rows):
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1100 640">',
             '<rect width="1100" height="640" fill="#f5f8fc"/>',
             '<g font-family="Microsoft YaHei, sans-serif" fill="#182a41">',
             '<text x="40" y="45" font-size="26" font-weight="700">候选排序与失败样本｜教学模拟</text>',
             '<text x="40" y="80" font-size="16">蓝：普通余弦　青：加入RI　橙色提示：质量关卡或歧义拒判；分数不是概率</text>']
    notes = ['U01：RI支持A，谱图首选B', 'U02：共洗脱，暂停鉴定', 'U03：前两名接近，补测']
    for j, sid in enumerate(('U01', 'U02', 'U03')):
        left = 40 + j*355
        note_color = '#182a41' if j == 0 else '#9c5210'
        parts.append(f'<text x="{left}" y="130" fill="{note_color}" font-size="17" font-weight="700">{notes[j]}</text>')
        rows = sorted([r for r in all_rows if r['sample'] == sid], key=lambda r: r['candidate'])
        for i, row in enumerate(rows):
            y = 190 + 125*i
            parts.append(f'<text x="{left}" y="{y}" font-size="18">候选{row["candidate"]}</text>')
            for offset, key, color in ((10, 'cosine', '#527dcc'), (37, 'score', '#16877e')):
                value = row[key]
                parts.append(f'<rect x="{left}" y="{y+offset}" width="{230*value:.2f}" height="18" fill="{color}"/>')
                parts.append(f'<text x="{left+240}" y="{y+offset+15}" font-size="15">{value:.4f}</text>')
    parts.append('<text x="40" y="600" font-size="16">限制：三例由人工设计，仅验证计算与拒判流程；不代表真实样品鉴定性能。</text></g></svg>')
    (OUT / 'comparison.svg').write_text('\n'.join(parts), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    if args.self_test:
        self_test()
    OUT.mkdir(exist_ok=True)
    spectra = {}
    for row in read_csv('spectra.csv'):
        spectrum = spectra.setdefault(row['spectrum_id'], {})
        mz, intensity = int(row['mz']), float(row['intensity'])
        spectrum[mz] = spectrum.get(mz, 0) + intensity
    candidates = read_csv('candidates.csv')
    offsets = {}
    for row in read_csv('anchors.csv'):
        offsets.setdefault(row['batch'], []).append(float(row['observed_rt_min']) - float(row['reference_rt_min']))
    shifts = {batch: median(values) for batch, values in offsets.items()}
    all_rows, decisions, sensitivity = [], [], []
    for peak in read_csv('peaks.csv'):
        sid = peak['sample_id']
        raw = float(peak['raw_rt_min'])
        rt = raw - shifts[peak['batch']]
        ri = lri(rt, float(peak['alkane_low_ref_min']), float(peak['alkane_high_ref_min']), int(peak['alkane_n']))
        rows = rank(spectra[sid], ri, spectra, candidates)
        baseline = max(rows, key=lambda row: row['cosine'])['candidate']
        for i, row in enumerate(rows, 1):
            all_rows.append(dict(sample=sid, rank=i, **row))
        outcome = dict(sample=sid, raw_rt_min=raw, aligned_rt_min=round(rt, 6),
                       ri=round(ri, 6), rs=float(peak['rs']), spectral_top=baseline,
                       fused_top=rows[0]['candidate'], gap=rows[0]['score']-rows[1]['score'],
                       decision=decision(rows, float(peak['rs'])))
        decisions.append(outcome)
        print(f'{sid}: RI={ri:.2f}, spectral={baseline}, fused={outcome["fused_top"]}, gap={outcome["gap"]:.6f}, {outcome["decision"]}')
        if sid == 'U01':
            for sigma in (5, 15, 30, 60):
                changed = rank(spectra[sid], ri, spectra, candidates, sigma)
                sensitivity.append(dict(sigma=sigma, top=changed[0]['candidate'],
                                        gap=changed[0]['score']-changed[1]['score'],
                                        decision=decision(changed, float(peak['rs']))))
    if args.self_test:
        assert decisions[0]['spectral_top'] == 'B' and decisions[0]['fused_top'] == 'A'
        assert all(d['decision'].startswith('拒判') for d in decisions[1:])
        assert sensitivity[-1]['decision'].startswith('拒判')
        print('Scenario checks passed: ranking reversal, quality refusal, ambiguity refusal, sensitivity.')
    write_csv('ranking.csv', all_rows)
    write_csv('decisions.csv', decisions)
    write_csv('sensitivity.csv', sensitivity)
    write_lab_data(decisions, all_rows)
    plot(all_rows)
    log = dict(time_utc=datetime.now(timezone.utc).isoformat(), python=platform.python_version(),
               parameters=dict(spectral_weight=.7, ri_weight=.3, sigma=15, min_rs=1,
                               min_score=.8, min_gap=.05, shift=shifts),
               data_identity='synthetic teaching data, not measured spectra',
               input_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DATA.glob('*.csv'))})
    (OUT / 'run_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=2), encoding='utf-8')
    report = ['# G10运行结果（模拟数据）', '', '| 样本 | RI | 谱图首选 | 融合首选 | 分差 | 决策 |', '|---|---:|---|---|---:|---|']
    for d in decisions:
        report.append(f'| {d["sample"]} | {d["ri"]:.2f} | {d["spectral_top"]} | {d["fused_top"]} | {d["gap"]:.6f} | {d["decision"]} |')
    report += ['', '## U01候选数值', '', '| 候选 | 余弦 | ΔRI | RI分数 | 融合分数 |', '|---|---:|---:|---:|---:|']
    for r in all_rows:
        if r['sample'] == 'U01':
            report.append(f'| {r["candidate"]} | {r["cosine"]:.6f} | {r["delta_ri"]:.1f} | {r["ri_score"]:.6f} | {r["score"]:.6f} |')
    report += ['', '## 容差敏感性', '', '| σ | 首选 | 分差 | 决策 |', '|---|---|---:|---|']
    for r in sensitivity:
        report.append(f'| {r["sigma"]} | {r["top"]} | {r["gap"]:.6f} | {r["decision"]} |')
    report += ['', '失败样本：U02的模拟Rs低于质量门槛；U03前两名差小于0.05。不能用任何排名覆盖质量拒判。', '', '运行环境和输入校验值见run_log.json。分数不代表身份概率；本例不提供真实性能评估。']
    (OUT / 'report.md').write_text('\n'.join(report), encoding='utf-8')


if __name__ == '__main__':
    main()
