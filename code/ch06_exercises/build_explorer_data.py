"""Build or verify the Chapter 6 browser snapshot from the archived CSVs."""
import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def csv_rows(path):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def snapshot(results):
    predictions = [
        [r['split'], int(r['seed']), r['model'], r['id'], r['name'], r['canonical_smiles'],
         float(r['measured_logS']), float(r['predicted_logS']), float(r['nearest_train_tanimoto']),
         int(r['n_heavy_atoms']), int(r['formal_charge'])]
        for r in csv_rows(results / 'esol/predictions.csv')
    ]
    descriptors = csv_rows(results / 'descriptors.csv')
    lines = ['/* Generated by code/ch06_exercises/build_explorer_data.py. */']
    for name, rows in [('EXPLORER', predictions), ('DESCRIPTOR', descriptors)]:
        payload = json.dumps(rows, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
        lines.append(f'window.CH06_{name}_DATA={payload};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path, default=ROOT / 'resources/annual/2026-2027/results/ch06')
    parser.add_argument('--output', type=Path, default=ROOT / 'assets/js/ch06-explorer-data.js')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = snapshot(args.results)
    if args.check:
        if args.output.read_text(encoding='utf-8') != content:
            parser.exit(1, 'Browser snapshot differs from archived CSVs.\n')
        print('Browser snapshot matches archived CSVs.')
    else:
        args.output.write_text(content, encoding='utf-8', newline='\n')
